"""Detection engine package for Mini-IDS.

Contains rule-based detectors, statistical anomaly detectors, and supervised ML models:
- PortScanDetector: Identifies TCP port scans (distinct destination ports).
- SynRateDetector: Identifies unusually high TCP SYN rates.
- TrafficAnomalyDetector: Identifies sudden surges in traffic byte or packet volume.
- HybridDetectionEngine: Correlates rules, ML models, and anomaly detection.
- CentralInferenceEngine: High-throughput inference and schema conformance.
"""

from dataclasses import asdict, dataclass
from typing import Optional, Union


@dataclass
class Alert:
    """Structured security alert generated by detection rules and ML engines."""

    timestamp: float
    rule_name: str
    src_ip: Optional[str]
    dst_ip: Optional[str]
    observed_value: Union[int, float]
    threshold: Union[int, float]
    window_seconds: float
    severity: str
    message: str
    detection_method: str = "HEURISTIC"
    model_version: Optional[str] = None
    confidence: Optional[float] = None
    anomaly_score: Optional[float] = None
    threat_score: Optional[float] = None
    prevention_action_id: Optional[str] = None

    def to_dict(self) -> dict:
        """Convert the alert instance to a standard Python dictionary."""
        return asdict(self)



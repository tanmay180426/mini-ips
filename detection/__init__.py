def __getattr__(name: str):
    """Lazy import for ResponsePolicyEngine to prevent circular import chains."""
    if name == "ResponsePolicyEngine":
        from detection.response_policy import ResponsePolicyEngine
        return ResponsePolicyEngine
    raise AttributeError(f"module 'detection' has no attribute '{name}'")

